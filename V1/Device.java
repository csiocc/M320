public class Device {
  
  private String name;
  private String hersteller;
  private float preis;
  private int id;
  private Boolean anLager;

  public Device(String name, String hersteller, float preis, int id, Boolean anLager) {
    this.name = name;
    this.hersteller = hersteller;
    this.preis = preis;
    this.id = id;
    this.anLager = anLager;
  }

  
  
}
